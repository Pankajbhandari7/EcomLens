export interface CategoryRules {
  fills: number[];
  shadows: boolean[];
  tones: ("white" | "soft-white" | "light-grey")[];
  labelPrefix: string;
}

export function getCategoryRules(categoryName: string | null): CategoryRules {
  if (!categoryName) {
    // Default fallback rules (zoomed out to imply lower volumetric weight)
    return {
      fills: [60, 65, 70, 75, 80],
      shadows: [false, true],
      tones: ["white", "soft-white"],
      labelPrefix: "volumetric optimized"
    };
  }

  const name = categoryName.toLowerCase();
  
  // Apparel (Western, Ethnic, Men's, Kids)
  if (name.includes("fashion") || name.includes("women") || name.includes("men")) {
    return {
      fills: [65, 68, 70, 72, 75], // Slightly zoomed out to reduce perceived volume (shipping optimization)
      shadows: [true],
      tones: ["white", "soft-white"],
      labelPrefix: "apparel (volumetric reduced)"
    };
  }

  // Electronics & Accessories
  if (name.includes("electronics") || name.includes("mobiles") || name.includes("appliances")) {
    return {
      fills: [70, 75, 78, 80], // Moderate crop so it doesn't look too bulky
      shadows: [false], 
      tones: ["white"], 
      labelPrefix: "tech (volumetric reduced)"
    };
  }

  // Bags, Luggage, Travel (High volumetric items)
  if (name.includes("bags") || name.includes("luggage") || name.includes("travel")) {
    return {
      fills: [55, 60, 65, 70], // Extra zoomed out to minimize perceived shipping bulk
      shadows: [true, false], 
      tones: ["white"], 
      labelPrefix: "luggage (low volumetric padding)"
    };
  }

  // Home, Kitchen, Beauty, Toys, Grocery
  if (name.includes("home") || name.includes("kitchen") || name.includes("beauty") || name.includes("wellness") || name.includes("toys") || name.includes("grocery")) {
    return {
      fills: [60, 65, 70, 75], // Zoomed out padding for context and perceived size reduction
      shadows: [true], 
      tones: ["white", "soft-white", "light-grey"], 
      labelPrefix: "lifestyle (volumetric reduced)"
    };
  }

  // Fallback
  return {
    fills: [60, 65, 70, 75, 80],
    shadows: [false, true],
    tones: ["white"],
    labelPrefix: "category optimized"
  };
}
